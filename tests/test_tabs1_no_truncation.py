"""TabS1 executed-design table: no truncated level lists, no dropped encoder.

These tests exist because the shipped 2026-08-19 TabS1 was generated by an
``lv()`` helper containing ``sorted(...)[:8]``. That silent truncation

  (a) dropped ``woe`` -- ninth alphabetically -- from the Simulation 1B encoder
      list, although woe ran to completion (57,600 rows, 100% SUCCESS);
  (b) cut the bucket-width list in ALL FOUR rows (1A 12->8, 1C exact 11->8,
      1C finite 11->8, 1B 15->8);

and a separate ``status == "SUCCESS"`` filter

  (c) reported 979,200 executed Simulation 1B rows instead of the executed
      1,094,400 = 979,200 SUCCESS + 115,200 SKIPPED_INELIGIBLE (the
      typed-absence oracle rows added under deviation D12).

The advisor's binding instruction is "The regenerated table must not truncate
level lists." Reintroducing any slice in ``run_sim1_tables._lv`` must fail
here. SIMULATION ONLY: nothing below runs a simulation cell; the parametrised
tests read the frozen raw output read-only and skip if it is absent.
"""
from __future__ import annotations

import ast
import inspect
import sys
import textwrap
from pathlib import Path

import pandas as pd
import pytest
import yaml

REPO = Path(__file__).resolve().parents[1]
if str(REPO / "scripts") not in sys.path:
    sys.path.insert(0, str(REPO / "scripts"))

import run_sim1_tables as T                                       # noqa: E402

OUTD = REPO / "simulation-results-ct2i"
RAW = OUTD / "raw"
TABD = OUTD / "11_SIM1_TABLES"
FREEZE = OUTD / "01_PROTOCOL_FREEZE.yaml"

ARMS = {"1A": "sim1a_replicates.csv", "1C exact": "sim1c_exact.csv",
        "1C finite": "sim1c_finite.csv", "1B": "sim1b_replicates.csv"}

# Executed level counts, re-derived from the frozen raw output. Independent of
# the generator so that a truncation there cannot also silence the check.
EXPECTED_LEVEL_COUNTS = {
    "1A": {"encoder": 7, "bucket_width": 12, "M": 2, "K": 2, "delta_eta": 3},
    "1C exact": {"encoder": 2, "bucket_width": 11, "M": 4, "activation_rate": 3},
    "1C finite": {"encoder": 5, "bucket_width": 11, "M": 4, "learner": 3},
    "1B": {"encoder": 9, "bucket_width": 15, "M": 2, "K": 3, "delta_eta": 3,
           "learner": 4, "n_train": 2},
}

SIM1B_EXECUTED_ROWS = 1_094_400
SIM1B_SUCCESS_ROWS = 979_200
SIM1B_SKIPPED_ROWS = 115_200


def _tab():
    p = TABD / "TabS1.csv"
    if not p.exists():
        pytest.skip("TabS1.csv not built")
    return pd.read_csv(p).set_index("component")


def _levels(cell):
    return [x for x in str(cell).split(", ") if x and x != "nan"]


# --------------------------------------------------------------------------
# 1. static: the truncation must not come back into the generator source
# --------------------------------------------------------------------------
def test_lv_source_contains_no_slice():
    """``_lv`` must contain no subscript slicing at all -- that is how [:8] hid."""
    tree = ast.parse(textwrap.dedent(inspect.getsource(T._lv)))
    slices = [n for n in ast.walk(tree) if isinstance(n, ast.Slice)]
    assert not slices, (
        "run_sim1_tables._lv contains slicing; the retired defect was "
        "sorted(...)[:8], which silently dropped woe and 7 bucket widths")


def test_protocol_declares_nine_sim1b_encoders():
    cfg = yaml.safe_load(FREEZE.read_text(encoding="utf-8"))
    frozen = tuple(sorted(cfg["simulation_1b"]["encoders"]))
    assert len(frozen) == 9
    assert "woe" in frozen
    assert frozen == T.SIM1B_PROTOCOL_ENCODERS


# --------------------------------------------------------------------------
# 2. the written table: every level list is complete
# --------------------------------------------------------------------------
@pytest.mark.parametrize("comp", list(EXPECTED_LEVEL_COUNTS))
def test_written_level_lists_are_not_truncated(comp):
    t = _tab()
    assert comp in t.index, f"TabS1 has no row for {comp}"
    for col, want in EXPECTED_LEVEL_COUNTS[comp].items():
        got = _levels(t.loc[comp, col])
        assert len(got) == want, (
            f"TabS1 {comp}.{col}: {len(got)} levels printed, {want} executed "
            f"-- truncated list {got}")


def test_written_sim1b_encoder_list_has_all_nine_including_woe():
    t = _tab()
    enc = _levels(t.loc["1B", "encoder"])
    assert len(enc) == 9
    assert "woe" in enc, "woe ran (57,600 rows, 100% SUCCESS) and must be listed"
    assert tuple(enc) == T.SIM1B_PROTOCOL_ENCODERS


def test_written_sim1b_bucket_widths_are_all_fifteen():
    t = _tab()
    w = [float(x) for x in _levels(t.loc["1B", "bucket_width"])]
    assert w == [10, 20, 30, 40, 60, 80, 120, 125, 160, 240, 250, 480, 500,
                 1000, 2000]


def test_written_sim1b_row_count_is_the_executed_count():
    t = _tab()
    assert int(t.loc["1B", "rows"]) == SIM1B_EXECUTED_ROWS
    assert int(t.loc["1B", "rows_success"]) == SIM1B_SUCCESS_ROWS


def test_written_sim1b_note_states_d3_and_pure_noise():
    n = str(_tab().loc["1B", "notes"]).lower()
    assert "d = 3" in n or "d=3" in n
    assert "every cell" in n
    assert "pure-noise" in n or "pure noise" in n
    assert "signal dimension" in n or "not the signal" in n


# --------------------------------------------------------------------------
# 3. the guard itself bites (no frozen raw needed)
# --------------------------------------------------------------------------
def test_assert_no_truncation_rejects_a_truncated_row():
    frame = pd.DataFrame({"encoder": T.SIM1B_PROTOCOL_ENCODERS,
                          "bucket_width": range(9)})
    good = {"encoder": ", ".join(T.SIM1B_PROTOCOL_ENCODERS),
            "bucket_width": ", ".join(str(i) for i in range(9))}
    T._assert_no_truncation(good, frame, "1B")            # must not raise
    bad = dict(good, encoder=", ".join(T.SIM1B_PROTOCOL_ENCODERS[:8]))
    with pytest.raises(SystemExit, match="truncated"):
        T._assert_no_truncation(bad, frame, "1B")


def test_assert_no_truncation_rejects_a_wrong_sim1b_encoder_set():
    enc = list(T.SIM1B_PROTOCOL_ENCODERS[:8]) + ["not_an_encoder"]
    frame = pd.DataFrame({"encoder": enc})
    row = {"encoder": ", ".join(enc)}
    with pytest.raises(SystemExit, match="frozen in 01_PROTOCOL_FREEZE"):
        T._assert_no_truncation(row, frame, "1B")


# --------------------------------------------------------------------------
# 4. raw provenance: the numbers the table asserts are the numbers on disk
# --------------------------------------------------------------------------
def test_raw_sim1b_executed_count_decomposition():
    p = RAW / ARMS["1B"]
    if not p.exists():
        pytest.skip("frozen raw sim1b not present")
    s = pd.read_csv(p, usecols=["status", "encoder"], low_memory=False)
    vc = s.status.value_counts()
    assert vc.get("SUCCESS", 0) == SIM1B_SUCCESS_ROWS
    assert vc.get("SKIPPED_INELIGIBLE", 0) == SIM1B_SKIPPED_ROWS
    assert len(s) == SIM1B_EXECUTED_ROWS
    woe = s[s.encoder == "woe"]
    assert len(woe) == 57_600
    assert (woe.status == "SUCCESS").all()
