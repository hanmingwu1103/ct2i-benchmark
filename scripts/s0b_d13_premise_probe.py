def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--section", default="all",
                    choices=["all", "params", "nesting", "twin", "variance"])
    ap.add_argument("--reps", type=int, default=50,
                    help="replicates per block for --section variance "
                         "(the frozen design uses 50; smaller values are "
                         "probes and must not be quoted)")
    ap.add_argument("--out", type=Path, default=None,
                    help="OPTIONAL json summary path; there is NO default "
                         "output file and it may not be inside the results "
                         "package")
    args = ap.parse_args(argv)
    if args.out is not None and PKG in args.out.resolve().parents:
        ap.error("refusing to write a probe summary into the results package")

    print("D13 PREMISE PROBE -- zero addendum cells, zero package writes")
    print(f"repo        : {REPO}")
    print(f"interpreter : {sys.executable}")
    ok = check_seed_rule()
    res = {"seed_rule_matches_runner": ok}
    if args.section in ("all", "params"):
        res["params"] = section_params()
    if args.section in ("all", "nesting"):
        res["nesting"] = section_nesting()
    if args.section in ("all", "twin"):
        res["twin"] = section_twin()
    if args.section in ("all", "variance"):
        res["variance"] = section_variance(args.reps)
    if args.out is not None:
        args.out.write_text(json.dumps(res, indent=2, default=str))
        print(f"\n[wrote] {args.out}")
    return 0 if ok else 1


