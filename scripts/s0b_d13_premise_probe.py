def transcribed_seed(block, replicate: int) -> int:
    """The seed rule as READ from run_sim1b_dense_addendum.addendum_seed."""
    h = int.from_bytes(
        hashlib.blake2b(repr(tuple(block)).encode(), digest_size=4).digest(),
        "little")
    return SEED_BASE_1BD + 1000 * (h % 1_000_000) + int(replicate)


def check_seed_rule() -> bool:
    ok = True
    for marg, tau, ni in BLOCKS:
        blk = RUN.addendum_block(marg, tau, ni)
        for r in (1, 2, 7, 50):
            if RUN.addendum_seed(blk, r) != transcribed_seed(blk, r):
                ok = False
    print(f"[seed rule] transcription == runner's addendum_seed : {ok}")
    return ok


def params(marg, tau, n_int, delta, rep):
    blk = RUN.addendum_block(marg, tau, n_int)
    s = RUN.addendum_seed(blk, rep)
    return s, CORE.draw_params(M_ADD, K_ADD, marg, tau, n_int, delta, s,
                               d_active=D_ADD)


def dmax(p, q) -> tuple[float, float]:
    da = float(np.max(np.abs(p.a - q.a)))
    db = 0.0
    if p.b or q.b:
        assert len(p.b) == len(q.b)
        db = max((float(np.max(np.abs(x - y))) for x, y in zip(p.b, q.b)),
                 default=0.0)
    return da, db


