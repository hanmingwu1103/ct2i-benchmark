PAIRS = [(1, 2), (1, 3), (2, 3), (1, 50), (25, 26), (49, 50)]


def section_params() -> dict:
    print("\n=== Q1  WITHIN one block, ACROSS replicates: does (a, b) move? ===")
    print(f"{'block(marg,tau,n_int)':<26} {'r1':>3} {'r2':>3} {'seed1':>11} "
          f"{'seed2':>11} {'max|da|':>10} {'max|db|':>10}")
    das, dbs, zero = [], [], 0
    for marg, tau, ni in BLOCKS:
        for r1, r2 in PAIRS:
            s1, p1 = params(marg, tau, ni, 0.0, r1)
            s2, p2 = params(marg, tau, ni, 0.0, r2)
            da, db = dmax(p1, p2)
            das.append(da)
            dbs.append(db)
            zero += int(da == 0.0)
            print(f"{str((marg, tau, ni)):<26} {r1:>3} {r2:>3} {s1:>11} "
                  f"{s2:>11} {da:>10.6f} {db:>10.6f}")
    out = {
        "n_pairs": len(das),
        "min_max_abs_da": float(min(das)),
        "max_max_abs_da": float(max(das)),
        "pairs_with_max_abs_da_exactly_zero": int(zero),
        "min_max_abs_db_where_b_exists": float(min([d for d in dbs if d > 0])
                                               if any(d > 0 for d in dbs) else 0.0),
    }
    print(f"\n  within-block replicate pairs checked            : {out['n_pairs']}"
          f"  (8 blocks x {len(PAIRS)} pairs)")
    print(f"  MIN over those pairs of max|a(r1) - a(r2)|      : "
          f"{out['min_max_abs_da']:.17g}")
    print(f"  MAX over those pairs of max|a(r1) - a(r2)|      : "
          f"{out['max_max_abs_da']:.17g}")
    print(f"  pairs with max|da| EXACTLY 0.0                  : "
          f"{out['pairs_with_max_abs_da_exactly_zero']} / {out['n_pairs']}")
    print("  (D13's premise -- one draw per block -- predicts "
          f"{out['n_pairs']} / {out['n_pairs']} exact zeros)")
    print("  max|db| is 0.0 exactly in the n_int = 0 blocks because no "
          "interaction array exists there.")

    print("\n=== Q2  WITHIN (block, replicate), ACROSS delta_eta and n_train ===")
    worst_de, worst_nt, cells = 0.0, 0, 0
    for marg, tau, ni in BLOCKS:
        for rep in (1, 2, 3, 17, 50):
            base_s, base_p = params(marg, tau, ni, DELTAS[0], rep)
            for de in DELTAS[1:]:
                s, p = params(marg, tau, ni, de, rep)
                assert s == base_s
                da, db = dmax(base_p, p)
                worst_de = max(worst_de, da, db)
                cells += 1
            for _nt in N_TRAINS:      # n_train is absent from the block key
                worst_nt = max(worst_nt, abs(
                    RUN.addendum_seed(RUN.addendum_block(marg, tau, ni), rep)
                    - base_s))
    out.update(delta_eta_cells_checked=cells,
               max_param_diff_across_delta_eta=float(worst_de),
               max_seed_diff_across_n_train=int(worst_nt))
    print(f"  (block, replicate, delta_eta) comparisons       : {cells}")
    print(f"  max |a| and |b| difference across delta_eta     : {worst_de:.17g}"
          f"   (exactly 0.0: {worst_de == 0.0})")
    print(f"  max seed difference across n_train levels       : {worst_nt}"
          f"   (n_train never enters the seed)")

    print("\n=== Q3  how many DISTINCT parameter draws at M=5, K=4? ===")
    seeds, sigs = set(), set()
    for marg, tau, ni in BLOCKS:
        for rep in range(1, 51):
            s, p = params(marg, tau, ni, 0.0, rep)
            seeds.add(s)
            sigs.add(p.a.tobytes() + b"|"
                     + b"|".join(x.tobytes() for x in p.b))
    n_scen = len(list(itertools.product(MARGINALS, TAUS, N_INTS, DELTAS, N_TRAINS)))
    out.update(distinct_blocks=len(BLOCKS), distinct_seeds=len(seeds),
               distinct_param_signatures=len(sigs), distinct_scenarios=n_scen)
    print(f"  distinct blocks                : {len(BLOCKS)}")
    print(f"  distinct seeds (8 blocks x 50) : {len(seeds)}")
    print(f"  distinct (a, b) signatures     : {len(sigs)}")
    print(f"  distinct scenarios             : {n_scen}")
    print("  => the independent unit is the DRAW (block, replicate): "
          f"{len(sigs)} per arm, not {len(BLOCKS)}.")
    return out


