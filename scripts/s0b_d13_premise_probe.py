FULL = CORE.enumerate_cells(K_ADD, M_ADD)
FID_HASH_SHARED_B0 = CORE.group_ids(CORE.hash_codes(FULL, K_ADD, 10, False))


def _rel_log_gap(marg, tau, n_int, delta, d, seed) -> float:
    """Exact population `relative_log_gap` for hash_shared/B0 (D14 definition)."""
    prm = CORE.draw_params(M_ADD, K_ADD, marg, tau, n_int, delta, seed,
                           d_active=d)
    act = CORE.enumerate_cells(K_ADD, d)
    pa = CORE.cell_probabilities(act, prm.p_marg)
    ea = CORE.impose_delta_eta(act, pa, CORE.eta_raw(act, prm), delta)
    pf = CORE.cell_probabilities(FULL, prm.p_marg)
    ids = np.zeros(len(FULL), dtype=np.int64)
    for j in range(d):
        ids = ids * K_ADD + FULL[:, j]
    eta = ea[ids]
    fid = FID_HASH_SHARED_B0
    rl_x = float((pf * CORE._binary_entropy(eta)).sum())
    n_f = int(fid.max()) + 1
    mass = np.bincount(fid, weights=pf, minlength=n_f)
    ws = np.bincount(fid, weights=pf * eta, minlength=n_f)
    eb = np.where(mass > 0, ws / np.where(mass > 0, mass, 1.0), 0.0)
    rl_z = float((mass * CORE._binary_entropy(eb)).sum())
    p_y = float((pf * eta).sum())
    h_y = float(CORE._binary_entropy(np.array([p_y]))[0])
    return (rl_z - rl_x) / (h_y - rl_x)


def _arm_seed(marg, tau, n_int, d, rep) -> int:
    if d == 5:
        return RUN.addendum_seed(RUN.addendum_block(marg, tau, n_int), rep)
    return CORE.dgp_block_seed("1B", (M_ADD, K_ADD, marg, tau, n_int), rep)


def section_variance(n_rep: int) -> dict:
    reps = range(1, n_rep + 1)
    print(f"\n=== Q6  between-block variance share, METHOD A "
          f"(exact population, E1a contrast, {n_rep} replicates) ===")
    bm, dv_collapse, dv_deltaind = [], [], []
    for marg, tau, ni in BLOCKS:
        v5 = np.array([[_rel_log_gap(marg, tau, ni, de, 5,
                                     _arm_seed(marg, tau, ni, 5, r))
                        for r in reps] for de in DELTAS])
        v3 = np.array([[_rel_log_gap(marg, tau, ni, de, 3,
                                     _arm_seed(marg, tau, ni, 3, r))
                        for r in reps] for de in DELTAS])
        bm.append(float(v5.mean() - v3.mean()))
        # A-collapse-first: collapse delta_eta within a draw, then vary the draw
        c5, c3 = v5.mean(axis=0), v3.mean(axis=0)
        dv_collapse.append(float((c5.var(ddof=1) + c3.var(ddof=1)) / n_rep))
        # A-delta-independent: per-delta variances averaged, divided again by 3
        per_de = [(v5[i].var(ddof=1) + v3[i].var(ddof=1)) / n_rep
                  for i in range(len(DELTAS))]
        dv_deltaind.append(float(np.mean(per_de) / len(DELTAS)))
    bm = np.array(bm)
    v_between = float(bm.var(ddof=1))
    out = {"method_A_block_means": [round(x, 6) for x in bm.tolist()],
           "method_A_var_block_means": v_between}
    for label, dv in (("A-collapse-first (recommended)", np.array(dv_collapse)),
                      ("A-delta-independent (as first published)",
                       np.array(dv_deltaind))):
        draw = float(dv.mean())
        fixed = max(v_between - draw, 0.0)
        share = fixed / v_between if v_between > 0 else float("nan")
        key = "share_collapse_first" if label.startswith("A-collapse") \
            else "share_delta_independent"
        out[key] = share
        out[key + "_draw_var"] = draw
        print(f"  {label}")
        print(f"    SD of the 8 block-mean contrasts        = "
              f"{bm.std(ddof=1):.6f}")
        print(f"    mean within-block DRAW SE of a block mean = "
              f"{np.sqrt(draw):.6f}")
        print(f"    implied FIXED-FACTOR (condition) SD      = "
              f"{np.sqrt(fixed):.6f}")
        print(f"    fixed-factor share of Var(block means)   = {share:.1%}")
    print(f"  block means: {np.round(bm, 5).tolist()}")

    print("\n=== Q6  between-block variance share, METHOD B "
          "(frozen twin, 48 scenario means) ===")
    d = _twin_frame()
    shares = []
    print(f"  {'encoder/learner':<22} {'quantity':<20} {'between':>8} "
          f"{'SE(8blk)':>11} {'SE(48sc)':>11} {'ratio':>6}")
    for enc, lrn in (("target", "logistic"), ("label", "logistic"),
                     ("hash_shared", "lightgbm"), ("onehot", "mlp")):
        q = d[(d.metric == "logloss") & (d.encoder == enc)
              & (d.learner == lrn) & (d.status == "SUCCESS")]
        if len(q) == 0:
            print(f"  {enc}/{lrn}: no rows")
            continue
        for col in ("representation_loss", "total_excess_risk"):
            sc = q.groupby(["block", "scenario_id"])[col].mean().reset_index()
            blk = sc.groupby("block")[col].mean()
            grand = float(blk.mean())
            v_tot = float(((sc[col] - grand) ** 2).mean())
            v_btw = float(((blk - grand) ** 2).mean())
            se48 = float(sc[col].std(ddof=1) / np.sqrt(len(sc)))
            se8 = float(blk.std(ddof=1) / np.sqrt(len(blk)))
            shares.append(v_btw / v_tot)
            print(f"  {enc + '/' + lrn:<22} {col:<20} {v_btw / v_tot:>7.1%} "
                  f"{se8:>11.4g} {se48:>11.4g} {se8 / se48:>6.2f}")
    out["method_B_shares"] = [float(s) for s in shares]
    out["method_B_min"] = float(min(shares))
    out["method_B_max"] = float(max(shares))
    print(f"  METHOD B range over the 8 encoder/learner/quantity combinations: "
          f"{min(shares):.1%} - {max(shares):.1%}")
    print("  METHOD B does NOT subtract draw noise, so it is an upper bound on "
          "between-block spread of a DIFFERENT quantity than method A.")
    return out


